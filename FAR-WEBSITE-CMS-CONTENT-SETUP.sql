create table if not exists public.far_ad_packages (
 id bigint generated by default as identity primary key,
 sort_order integer not null default 0,
 name text not null,
 price numeric(10,2) not null default 0,
 plays_per_day integer not null default 0,
 description text not null default '',
 includes text not null default '',
 buy_url text,
 active boolean not null default true,
 updated_at timestamptz not null default now()
);
alter table public.far_ad_packages enable row level security;
drop policy if exists "public can read FAR ad packages" on public.far_ad_packages;
create policy "public can read FAR ad packages" on public.far_ad_packages for select to anon,authenticated using (active=true);
drop policy if exists "FAR admins can manage ad packages" on public.far_ad_packages;
create policy "FAR admins can manage ad packages" on public.far_ad_packages for all to authenticated
using (exists(select 1 from public.far_admins a where a.user_id=auth.uid() and lower(coalesce(a.role,'')) in ('owner','deputy_manager')))
with check (exists(select 1 from public.far_admins a where a.user_id=auth.uid() and lower(coalesce(a.role,'')) in ('owner','deputy_manager')));

