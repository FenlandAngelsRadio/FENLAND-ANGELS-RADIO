-- FAR Website CMS - editable public content
create table if not exists public.far_site_content (
  content_key text primary key,
  section text not null default 'general',
  label text not null,
  value text not null default '',
  value_type text not null default 'text' check (value_type in ('text','textarea','url','email','phone','number')),
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);
alter table public.far_site_content enable row level security;
drop policy if exists "public can read FAR site content" on public.far_site_content;
create policy "public can read FAR site content" on public.far_site_content for select to anon,authenticated using (true);
drop policy if exists "FAR admins can manage site content" on public.far_site_content;
create policy "FAR admins can manage site content" on public.far_site_content for all to authenticated
using (exists(select 1 from public.far_admins a where a.user_id=auth.uid() and lower(coalesce(a.role,'')) in ('owner','deputy_manager')))
with check (exists(select 1 from public.far_admins a where a.user_id=auth.uid() and lower(coalesce(a.role,'')) in ('owner','deputy_manager')));

